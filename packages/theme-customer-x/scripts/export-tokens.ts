/**
 * Emits the brand tokens as plain JSON and CSS custom properties so tools
 * outside Backstage (dashboards, templates, bots) can match the portal.
 *
 *   yarn workspace @globallogicuki/backstage-theme-customer-x tokens
 *
 * Writes dist-tokens/tokens.json and dist-tokens/tokens.css. Bundled with
 * esbuild (already in the repo via @backstage/cli) so it can import the
 * theme's TypeScript sources directly.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  brand,
  font,
  fontFamily,
  monoFontFamily,
  neutralsDark,
  neutralsLight,
  radius,
  shadow,
  statusDark,
  statusLight,
} from '../src/tokens';
import { dark, light } from '../src/theme/modes';

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, '..', 'dist-tokens');
mkdirSync(out, { recursive: true });

const semantic = (m: typeof light) => ({
  heading: m.heading,
  accentText: m.accentText,
  accentWash: m.accentWash,
  link: m.link,
  linkHover: m.linkHover,
  primary: m.primary,
  secondary: m.secondary,
  nav: m.nav,
  tint: m.tint,
});

const json = {
  $schema: 'https://design-tokens.github.io/community-group/format/',
  brand,
  font: { family: fontFamily, mono: monoFontFamily, size: font },
  radius,
  light: { neutrals: neutralsLight, status: statusLight, shadow: shadow.light, ...semantic(light) },
  dark: { neutrals: neutralsDark, status: statusDark, shadow: shadow.dark, ...semantic(dark) },
};
writeFileSync(join(out, 'tokens.json'), JSON.stringify(json, null, 2) + '\n');

const flat = (obj: Record<string, unknown>, prefix: string): string[] =>
  Object.entries(obj).flatMap(([k, v]) =>
    typeof v === 'object' && v !== null
      ? flat(v as Record<string, unknown>, `${prefix}-${k}`)
      : [`  ${prefix}-${k}: ${typeof v === 'number' ? `${v}px` : v};`],
  );

const css = [
  '/* Accelerate design tokens — generated by scripts/export-tokens.ts; do not edit. */',
  ':root {',
  ...flat(brand, '--accel-brand'),
  ...flat(font, '--accel-font'),
  `  --accel-font-family: ${fontFamily};`,
  `  --accel-font-mono: ${monoFontFamily};`,
  ...flat(radius, '--accel-radius'),
  ...flat({ neutrals: neutralsLight, status: statusLight, ...semantic(light) }, '--accel'),
  '}',
  '[data-theme="dark"], .dark {',
  ...flat({ neutrals: neutralsDark, status: statusDark, ...semantic(dark) }, '--accel'),
  '}',
  '',
].join('\n');
writeFileSync(join(out, 'tokens.css'), css);

console.log(`wrote ${join(out, 'tokens.json')} and tokens.css`);
